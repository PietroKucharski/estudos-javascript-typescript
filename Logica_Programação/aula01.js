/*
Operadores de comparação
> -> maior que
< -> menor que
>= -> maior ou igual
<= -> menor ou igual
== -> igual -> Não é utilizado por não identificar o tipo de dado
!= -> diferente --> Não é utilizado por não identificar o tipo de dado
=== -> igual estritamente -> Verifica a igualdade e identifica o tipo de dado
!== -> diferente estritamente -> Verifica a diferença e identifica o tipo de dado
*/

let expressao = 10 > 5 // A variável expressao recebe o resultado da comparação 10 > 5 (true ou false)
console.log(expressao)

expressao = 10 < 5
console.log(expressao)

expressao = 10 >= 5
console.log(expressao)

expressao = 10 <= 5
console.log(expressao)

expressao = 10 == 5
console.log(expressao)

expressao = 10 != 5
console.log(expressao)

expressao = 10 === 5
console.log(expressao)

expressao = 10 !== 5
console.log(expressao)
